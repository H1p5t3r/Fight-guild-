"""Compile authored sprite collision / starter move data to integer-only C++ tables."""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
# Smear slots are reserved for schema compatibility; transition smearing is removed.
FIELDS = 'button category direction motion air startup active recovery damage hitstun blockstun hitstop pushback reach bottom height specialCancel jumpCancel whiffCancel selfCancel advance simpleDirection simpleButton normalRoutes commandRoutes hitLevel chipDamage guardBreak counterHitstun counterHitstop reversalEligible hitboxBack airPushback blockPushback launch airLaunch knockdown knockdownFrames wakeupFrames wallDamage throwRange enabled artPose followFrom followFrom2 followHit travelSpeed inertiaPercent pullFrames pullGap hitAngle normalCancelStart normalCancelEnd specialCancelStart specialCancelEnd jumpCancelStart jumpCancelEnd followCancelStart followCancelEnd cancelOn starterProration comboScaling minimumDamage landingRecovery attackLevel counterTier counterVulnerable counterFreezeFrames counterSlowFrames projectileKind projectileSpawnFrame projectileSpeedX projectileSpeedY projectileGravity projectileLife projectileOffsetX projectileOffsetY projectileWidth projectileHeight projectileHits projectileRehit projectileDurability projectilePersist projectileMelee smearMode smearPart smearStretch smearFrame1 smearFrame2 smearFrame3 smearFrame4 hurtMaskWindup hurtMaskActive hurtMaskRecovery mechanic tetherSpeed tetherFrames bleedInitial bleedTickDamage bleedTickFrames bleedDuration bleedBlockPercent bleedCap variantStartup variantActive variantRecovery variantDamage variantRange variantSpeed variantLift variantHitstun variantKnockdown stanceRequired stanceChange actionType holdFollow holdFrame holdButton guardFollow proximityMove proximityRange startupTravel diveSpeedX diveSpeedY groundBounce wallBounce crumpleFrames airCounterKnockdown hurtWindowStart hurtWindowEnd hurtWindowMask semiAirStart semiAirEnd armorFrames armorHits grabFrames finishArtPose finishArtFrame'.split()
MOBILITY = 'forwardStyle walkSpeed runSpeed runAcceleration stepSpeed stepFrames backSpeed backFrames attackFriction backStyle backWalkSpeed backRunSpeed jumpSpeed jumpForwardSpeed jumpBackSpeed gravity airJumps prejumpFrames airDashEnabled airBackdashEnabled airDashStyle airBackdashStyle airDashSpeed airBackdashSpeed airDashFrames airBackdashFrames airDashUses hoverHeight hoverRiseSpeed teleportDistance backTeleportDistance teleportStartup fdEnabled fdPushPercent fdDrain fdAirDrain fdBlockCost smearMode smearPart smearStretch airDashPauseFrames airBackdashPauseFrames'.split()
PHASES = {'active': 12, 'windup': 6, 'block': 6, 'signature_windup': 32, 'signature_active': 32, 'ready': 1, 'walk': 8, 'run': 8, 'stance': 4, 'knockdown': 6, 'knockdown_back': 6, 'idle': 4, 'crouch_idle': 4}
HURT_REGIONS = ('legs', 'torsoArms', 'head', 'extension')


def hurt_rectangles(pose, context):
    """Fixed body roles, with one optional extension. Never truncate authored boxes."""
    regions = pose.get('hurt')
    if not isinstance(regions, dict) or set(regions) not in (set(HURT_REGIONS[:3]), set(HURT_REGIONS)):
        raise ValueError(f'{context}: hurtboxes require legs, torsoArms and head, with only one optional extension (4 maximum)')
    if ('extension' in regions) != bool(pose.get('extensionFor', '').strip()):
        raise ValueError(f'{context}: describe the extended body part only when an extension hurtbox is present')
    return [regions[key] for key in HURT_REGIONS if key in regions]


def compile_data():
    collision = json.loads((ROOT / 'godot/data/fighter_collision.json').read_text())
    art = json.loads((ROOT / 'godot/assets/fighters/manifest.json').read_text())
    tuning = json.loads((ROOT / 'godot/data/starter_moves.json').read_text())
    assert collision['version'] == 2 and tuning['version'] == 1
    assert len(collision['fighters']) == len(art['fighters']) == len(tuning['characters']) == 6
    hurt, push, moves, geometry, mobility, signatures, locomotion = [], [], [], [], [], [], []
    docs = ['# Preliminary move data', '', 'Generated by `python scripts/generate-combat-data.py`. Edit `godot/data/starter_moves.json` for defaults, or use the in-game Move editor for local tuning. These are first-pass values, not final balance.', '', 'Startup minimums at 60 Hz: **2 frames for throws**, **3 for P normals** (normal or command), **5 for other attacks**. Standard ground and air throws start in 2 frames; command-grab timings remain individually authored. Active frame 1 is the startup-numbered tick. Block advantage below assumes first-active contact of the final hit; air/projectile advantage depends on contact timing. No invulnerability is implied by reversal eligibility.', '', 'Moves without dedicated signature art reuse the button strike rectangle. Fillet/Shark signatures use their own body/strike geometry; hooks use eight narrow moving rectangles along the spear, with a harmless rope. See [signature behavior and inputs](signature-moves.md). Weapons can deal damage but never extend hurtboxes. 2D is a universal low sweep; 4P+K and 6P+K are universal ground throws. These new slots reuse existing button art pending dedicated animation. Ground/air strike push is a distance budget in pixels, travelled over six action ticks and stopped by wall contact; block push is contact displacement. Launch is upward pixels per tick. KD: 0 none, 1 soft, 2 hard; down/wake durations are ticks.', '']
    for body, fighter, character in zip(collision['fighters'], art['fighters'], tuning['characters']):
        assert body['name'] == fighter['name'] == character['name']
        poses, strikes = [], {}
        signatures.append(len(fighter.get('signature_active',{}).get('frames',[])))
        has_motion = all(phase in fighter for phase in ('ready', 'walk', 'run'))
        assert has_motion or not any(phase in fighter for phase in ('ready', 'walk', 'run'))
        locomotion.append(8 if has_motion else 0)
        for phase, count in PHASES.items():
            if phase not in fighter:
                assert phase.startswith('signature_') or phase in ('ready', 'walk', 'run', 'stance', 'idle', 'crouch_idle')
                poses.extend(['{0, {}}'] * count)
                continue
            sheet = fighter[phase]
            assert len(body['poses'][phase]) == len(sheet['frames']) <= count
            geometry.append([sheet['body_height'], [[f['pivot'],f.get('body_height',sheet['body_height'])] for f in sheet['frames']]])
            for i, authored in enumerate(body['poses'][phase]):
                pivot = sheet['frames'][i]['pivot']
                height = sheet['frames'][i].get('body_height',sheet['body_height'])

                def convert(rect):
                    assert len(rect) == 4 and all(type(v) is int for v in rect)
                    x1, y1, x2, y2 = rect
                    assert x2 > x1 and y2 > y1
                    # Outward rounding: stable integer geometry on every target.
                    lo = lambda n: n * 15000 // height
                    hi = lambda n: -(-n * 15000 // height)
                    return [lo(x1-pivot[0]), lo(pivot[1]-y2), hi(x2-pivot[0]), hi(pivot[1]-y1)]

                boxes = [convert(b) for b in hurt_rectangles(authored, f"{body['name']} / {phase} / {i}")]
                poses.append('{' + str(len(boxes)) + ', {' + ', '.join('{' + ','.join(map(str, b)) + '}' for b in boxes) + '}}')
                if 'strike' in authored:
                    assert (phase == 'active' and 1 <= i <= 5) or phase == 'signature_active'
                    strikes[(phase, i)] = convert(authored['strike'])
            poses.extend(['{0, {}}'] * (count-len(sheet['frames'])))
        hurt.append('    {\n        ' + ',\n        '.join(poses) + '\n    }')
        p = body['push']
        assert all(type(v) is int and 0 < v < 20000 for v in p.values())
        push.append('    {' + ','.join(str(p[k]) for k in ['halfWidth', 'standingHeight', 'crouchingHeight', 'airHeight', 'airBottom']) + '}')
        char_moves = []
        assert len(character['moves']) == 45
        assert set(character['movement']) == set(MOBILITY)
        mobility.append('    {{' + ','.join(str(character['movement'][k]) for k in MOBILITY) + '}}')
        docs.extend(['## ' + character['name'], '', '| Move | Start | Active | Recovery | Damage | Hitstun | Blockstun | On block | Stop | Ground / air / block push px | Ground / air launch px/f | KD / down / wake | Hitbox (back, bottom → front, top), px |', '|---|---:|---:|---:|---:|---:|---:|---:|---:|---|---|---|---|'])
        for move in character['moves']:
            minimum = 2 if move['category'] == 4 else 3 if move['button'] == 0 and move['category'] in (0, 1) else 5
            assert move['startup'] >= minimum
            assert move['variantStartup'] >= (2 if move['mechanic'] == 2 else 5)
            assert move['hitPose'] == 1 + move['button']
            key = ('signature_active', move['artPose']-1) if move['artPose'] else ('active', move['hitPose'])
            back, bottom, reach, top = strikes[key]
            if move['hitAngle']:
                # Diagonal spears travel from the hand to the authored reach. The rope never hits.
                back, bottom, reach, top = move['path']
            if move['category'] == 4:
                back, bottom, reach, top = 0, 0, p['halfWidth'] + move['throwRange'], p['standingHeight']
            if 'geometry' in move: back, bottom, reach, top = move['geometry']
            m = dict(move, hitboxBack=back, bottom=bottom, reach=reach, height=top-bottom)
            m.pop('path', None)
            m.pop('geometry', None)
            m.pop('hitboxTimeline', None)
            m.pop('hurtboxes', None)
            assert back < reach and reach > 0
            assert set(m) == set(FIELDS) | {'id', 'hitPose'}
            char_moves.append('        {{' + ','.join(str(m[k]) for k in FIELDS) + '}}')
            if not m['enabled']: continue
            final_start, stun, seen = 1, m['blockstun'], {1}
            track = move.get('hitboxTimeline', {})
            if track.get('multiHit'):
                for key in track['keys']:
                    if key['frame'] > m['active']: break
                    if key['boxes'] == []: continue
                    if key['hit'] not in seen:
                        seen.add(key['hit']); final_start = key['frame']
                        stun = m['blockstun'] if key['blockstun'] < 0 else key['blockstun']
            advantage = stun - (m['active'] - final_start + m['recovery'])
            docs.append('| ' + ' | '.join(str(m[k]) for k in ['id', 'startup', 'active', 'recovery', 'damage', 'hitstun', 'blockstun']) + f" | {advantage:+d} | {m['hitstop']} | {m['pushback']/100:g} / {m['airPushback']/100:g} / {m['blockPushback']/100:g} | {m['launch']/100:g} / {m['airLaunch']/100:g} | {m['knockdown']} / {m['knockdownFrames']} / {m['wakeupFrames']} | {back/100:.1f}, {bottom/100:.1f} → {reach/100:.1f}, {top/100:.1f} |")
        docs.append('')
        moves.append('    {\n' + ',\n'.join(char_moves) + '\n    }')
    digest = int.from_bytes(hashlib.sha256(json.dumps([collision, geometry], sort_keys=True).encode()).digest()[:4], 'big')
    header = '// Generated by scripts/generate-combat-data.py; edit godot/data sources.\n#pragma once\nnamespace fight {\n'
    header += 'struct PoseBoxes { int count; Box boxes[MAX_HURTBOXES]; };\nstruct PushProfile { int half_width, standing, crouching, air, air_bottom; };\n'
    header += f'constexpr unsigned COLLISION_HASH = {digest}u;\n'
    header += 'constexpr int SIGNATURE_POSES[CHARACTER_COUNT] = {' + ','.join(map(str, signatures)) + '};\n'
    header += 'constexpr int LOCOMOTION_POSES[CHARACTER_COUNT] = {' + ','.join(map(str, locomotion)) + '};\n'
    offsets = [sum(list(PHASES.values())[:i]) for i in range(len(PHASES))]
    counts = [','.join(str(len(f.get(p, {}).get('frames', []))) for p in PHASES) for f in art['fighters']]
    header += f'constexpr int POSE_PHASE_COUNT = {len(PHASES)};\n'
    header += 'constexpr int POSE_OFFSETS[POSE_PHASE_COUNT] = {' + ','.join(map(str, offsets)) + '};\n'
    header += 'constexpr int POSE_COUNTS[CHARACTER_COUNT][POSE_PHASE_COUNT] = {' + ','.join('{' + c + '}' for c in counts) + '};\n'
    header += f'constexpr PoseBoxes HURT_POSES[CHARACTER_COUNT][{sum(PHASES.values())}] = {{\n' + ',\n'.join(hurt) + '\n};\n'
    header += 'constexpr Mobility STARTER_MOBILITY[CHARACTER_COUNT] = {\n' + ',\n'.join(mobility) + '\n};\n'
    header += 'constexpr PushProfile PUSH_PROFILES[CHARACTER_COUNT] = {\n' + ',\n'.join(push) + '\n};\n'
    tracks=[]
    for character in tuning['characters']:
        entries=[]
        for move in character['moves']:
            track=move.get('hitboxTimeline',{'multiHit':False,'keys':[]}); keys=[]
            for key in track['keys']:
                boxes=key.get('boxes'); coords=', '.join('{'+','.join(map(str,b))+'}' for b in boxes or [])
                values=[key['frame'],key['hit'],len(boxes) if boxes is not None else -1]+[key.get(k,-1) for k in ['damage','hitstun','blockstun','hitstop']]
                keys.append('{'+','.join(map(str,values))+', {'+coords+'}}')
            entries.append('{'+str(int(track['multiHit']))+','+str(len(keys))+', {'+','.join(keys)+'}}')
        tracks.append('{'+','.join(entries)+'}')
    header += 'constexpr MoveHit STARTER_HITS[CHARACTER_COUNT][MOVE_COUNT] = {'+','.join(tracks)+'};\n'
    header += 'constexpr Move STARTER_MOVES[CHARACTER_COUNT][MOVE_COUNT] = {\n' + ',\n'.join(moves) + '\n};\n}\n'
    return {ROOT / 'core/combat_data.h': header, ROOT / 'docs/move-stats.md': '\n'.join(docs) + '\n'}


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Fail if generated files are stale')
    args = parser.parse_args()
    for path, content in compile_data().items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f'Stale generated file: {path.relative_to(ROOT)}; run {Path(__file__).name}')
        else:
            path.write_text(content)
    print('Combat data verified: 399 poses (3 body boxes + at most 1 extension), 6 movement/push profiles, 270 move slots, startup minimums: throws 2f / P normals 3f / other attacks 5f.')
