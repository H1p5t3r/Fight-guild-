#!/usr/bin/env python3
"""Compile authored sprite collision / starter move data to integer-only C++ tables."""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FIELDS = 'button category direction motion air startup active recovery damage hitstun blockstun hitstop pushback reach bottom height specialCancel jumpCancel whiffCancel selfCancel advance simpleDirection simpleButton normalRoutes commandRoutes hitLevel chipDamage guardBreak counterHitstun counterHitstop reversalEligible hitboxBack'.split()
PHASES = {'active': 12, 'windup': 6, 'block': 6}


def compile_data():
    collision = json.loads((ROOT / 'godot/data/fighter_collision.json').read_text())
    art = json.loads((ROOT / 'godot/assets/fighters/manifest.json').read_text())
    tuning = json.loads((ROOT / 'godot/data/starter_moves.json').read_text())
    assert collision['version'] == tuning['version'] == 1
    assert len(collision['fighters']) == len(art['fighters']) == len(tuning['characters']) == 6
    hurt, push, moves, geometry = [], [], [], []
    docs = ['# Preliminary move data', '', 'Generated by `python scripts/generate-combat-data.py`. Edit `godot/data/starter_moves.json` for defaults, or use the in-game Move editor for local tuning. These are first-pass values, not final balance.', '', 'All startup is at least **5 frames** at 60 Hz. Active frame 1 is the startup-numbered tick. Block advantage below assumes first-active-frame contact: blockstun − (active − 1 + recovery). No invulnerability is implied by reversal eligibility.', '', 'Hitboxes follow the currently shared button art; crouching, command, special and aerial slots reuse that button’s strike rectangle until their own animations exist. Weapons can deal damage but never extend hurtboxes. All attacks currently use mid guard level; universal overhead/anti-air/throw design remains deferred.', '']
    for body, fighter, character in zip(collision['fighters'], art['fighters'], tuning['characters']):
        assert body['name'] == fighter['name'] == character['name']
        poses, strikes = [], {}
        for phase, count in PHASES.items():
            sheet = fighter[phase]
            assert len(body['poses'][phase]) == len(sheet['frames']) == count
            geometry.append([sheet['body_height'], [f['pivot'] for f in sheet['frames']]])
            for i, authored in enumerate(body['poses'][phase]):
                pivot = sheet['frames'][i]['pivot']
                height = sheet['body_height']

                def convert(rect):
                    assert len(rect) == 4 and all(type(v) is int for v in rect)
                    x1, y1, x2, y2 = rect
                    assert x2 > x1 and y2 > y1
                    # Outward rounding: stable integer geometry on every target.
                    lo = lambda n: n * 15000 // height
                    hi = lambda n: -(-n * 15000 // height)
                    return [lo(x1-pivot[0]), lo(pivot[1]-y2), hi(x2-pivot[0]), hi(pivot[1]-y1)]

                boxes = [convert(b) for b in authored['hurt']]
                assert 1 <= len(boxes) <= 12
                poses.append('{' + str(len(boxes)) + ', {' + ', '.join('{' + ','.join(map(str, b)) + '}' for b in boxes) + '}}')
                if 'strike' in authored:
                    assert phase == 'active' and 1 <= i <= 5
                    strikes[i] = convert(authored['strike'])
        hurt.append('    {\n        ' + ',\n        '.join(poses) + '\n    }')
        p = body['push']
        assert all(type(v) is int and 0 < v < 20000 for v in p.values())
        push.append('    {' + ','.join(str(p[k]) for k in ['halfWidth', 'standingHeight', 'crouchingHeight', 'airHeight', 'airBottom']) + '}')
        char_moves = []
        assert len(character['moves']) == 22
        docs.extend(['## ' + character['name'], '', '| Move | Start | Active | Recovery | Damage | Hitstun | Blockstun | On block | Stop | Push px | Hitbox (back, bottom → front, top), px |', '|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---|'])
        for move in character['moves']:
            assert move['startup'] >= 5
            assert move['hitPose'] == 1 + move['button']
            back, bottom, reach, top = strikes[move['hitPose']]
            m = dict(move, hitboxBack=back, bottom=bottom, reach=reach, height=top-bottom)
            assert back < reach and reach > 0
            assert set(m) == set(FIELDS) | {'id', 'hitPose'}
            char_moves.append('        {{' + ','.join(str(m[k]) for k in FIELDS) + '}}')
            advantage = m['blockstun'] - (m['active'] - 1 + m['recovery'])
            docs.append('| ' + ' | '.join(str(m[k]) for k in ['id', 'startup', 'active', 'recovery', 'damage', 'hitstun', 'blockstun']) + f" | {advantage:+d} | {m['hitstop']} | {m['pushback']/100:g} | {back/100:.1f}, {bottom/100:.1f} → {reach/100:.1f}, {top/100:.1f} |")
        docs.append('')
        moves.append('    {\n' + ',\n'.join(char_moves) + '\n    }')
    digest = int.from_bytes(hashlib.sha256(json.dumps([collision, geometry], sort_keys=True).encode()).digest()[:4], 'big')
    header = '// Generated by scripts/generate-combat-data.py; edit godot/data sources.\n#pragma once\nnamespace fight {\n'
    header += 'struct PoseBoxes { int count; Box boxes[12]; };\nstruct PushProfile { int half_width, standing, crouching, air, air_bottom; };\n'
    header += f'constexpr unsigned COLLISION_HASH = {digest}u;\n'
    header += 'constexpr PoseBoxes HURT_POSES[CHARACTER_COUNT][24] = {\n' + ',\n'.join(hurt) + '\n};\n'
    header += 'constexpr PushProfile PUSH_PROFILES[CHARACTER_COUNT] = {\n' + ',\n'.join(push) + '\n};\n'
    header += 'constexpr Move STARTER_MOVES[CHARACTER_COUNT][MOVE_COUNT] = {\n' + ',\n'.join(moves) + '\n};\n}\n'
    return {ROOT / 'core/combat_data.h': header, ROOT / 'docs/move-stats.md': '\n'.join(docs) + '\n'}


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Fail if generated files are stale')
    args = parser.parse_args()
    for path, content in compile_data().items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f'Stale generated file: {path.relative_to(ROOT)}; run {Path(__file__).name}')
        else:
            path.write_text(content)
    print('Combat data verified: 144 poses, 6 push profiles, 132 move definitions, startup >= 5f.')
